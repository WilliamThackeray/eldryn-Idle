function at(id: string): number {
  return LEVEL[id] ?? 1
}

const clubs: ActivityDef[] = [
  { id: 'club', name: 'Club', inputs: [stack('logs')], level: at('craft-club') },
  { id: 'greatclub', name: 'Greatclub', inputs: [stack('logs')], level: at('craft-greatclub') },
  { id: 'quarterstaff', name: 'Quarterstaff', inputs: [stack('logs', 2)], level: at('craft-quarterstaff') },
].map((spec, index) =>
  activity({
    skillId: 'woodcraft',
    id: `craft-${spec.id}`,
    name: `Craft ${spec.name}`,
    description: `Shape ${spec.name.toLowerCase()}.`,
    requiredLevel: spec.level,
    inputs: spec.inputs,
    outputs: [drop(spec.id as ItemId)],
    category: 'Weapons',
    sortOrder: index,
  }),
)

function bow(
  id: string,
  name: string,
  wood: ItemId,
  qty: number,
  output: ItemId,
  category: string,
): ActivityDef {
  return activity({
    skillId: 'woodcraft',
    id,
    name,
    description: `Shape ${name.replace(/^Fletch /, '').toLowerCase()}.`,
    requiredLevel: at(id),
    inputs: [stack(wood, qty)],
    outputs: [drop(output)],
    category,
  })
}

