import { magicBonusForRarity, type GearMaterial, type ItemDef, type WeaponGear } from './types'

function weapon(
  id: string,
  name: string,
  description: string,
  buyPrice: number,
  gear: WeaponGear,
  material?: GearMaterial,
): ItemDef {
  return {
    id,
    name,
    description,
    category: 'gear',
    rarity: 'common',
    stackable: true,
    sellValue: Math.max(1, Math.floor(buyPrice / 2)),
    tags: ['weapon'],
    gear: {
      slot: 'mainHand',
      material,
      magicBonus: magicBonusForRarity('common'),
      weapon: gear,
    },
  }
}

